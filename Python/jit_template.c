#define A (cx->a)

void
_PyJitTemplate_Branch(_PyJitWordCx *cx, int cond)
{
    _PyJitAsm_Jcc(A, (_PyJitCond)cond, cx->target);
}

/* The error exit: publish the word, then leave with the transfer of the
   handler's raise */
void
_PyJitTemplate_Raise(_PyJitWordCx *cx, _PyJitLabel label)
{
    _PyJitAsm_Bind(A, label);
    cx->live = 0;
    cx->live_xmm = 0;
    _PyJitArg args[2] = {_PyJitArg_GPR(_PyJit_TSTATE), _PyJitArg_GPR(_PyJit_FRAME)};
    _PyJitLower_Call(cx, _PyEval_JitRaiseExit, 1, 2, args, _PyJitArg_NONE);
    _PyJitAsm_Jmp(A, cx->leave);
}

/* dst := base + index * size, dst distinct from base and index */
void
_PyJitTemplate_PtrAdd(_PyJitWordCx *cx, _PyJitReg dst, _PyJitReg base,
                      _PyJitReg index, size_t size)
{
    int scale = size == 1 ? 0 : size == 2 ? 1 : size == 4 ? 2 : size == 8 ? 3 : -1;
    if (scale >= 0) {
        _PyJitAsm_Lea(A, dst, _PyJitMem_Indexed(base, index, scale, 0));
        return;
    }
    assert(dst != base && dst != index);
    _PyJitAsm_ImulRRI(A, dst, index, (int32_t)size);
    _PyJitAsm_AluRR(A, _PyJitAlu_ADD, dst, base);
}

/* dst /= size for an exact multiple of size, a power of two */
static void
_PyJitTemplate_SarLog2(_PyJitWordCx *cx, _PyJitReg dst, size_t size)
{
    assert(size != 0 && (size & (size - 1)) == 0);
    int shift = _Py_bit_length((unsigned long)size) - 1;
    if (shift > 0) {
        _PyJitAsm_ShiftRI(A, _PyJitShift_SAR, dst, shift);
    }
}

