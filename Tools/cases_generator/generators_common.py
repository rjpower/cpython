# Macros of the DSL that name the instruction stream or the feedback entry.
# Each generator expands them for its form of the code: these are the stack
# interpreter's expansions, and ir_generator.IR_INSTRUCTION_MACROS holds the
# register IR's. "{0}" and "{1}" stand for the arguments, "{0p}" for the
# first argument in parentheses unless it is a single token.
STACK_INSTRUCTION_MACROS = {
    # The header of the instruction's feedback entry, which holds its counter.
    "FB_COUNTER": "_PyFb_Header(this_instr)",
    # The 16-bit taken history of a conditional branch.
    "FB_BRANCH": "this_instr[1].cache",
    # The entry header of the instruction at {0} once it runs as opcode {1}.
    "FB_HEADER_OF": "_PyFb_Header({0})",
    # The opcode and oparg of the instruction at {0}.
    "INSTR_OPCODE": "{0p}->op.code",
    "INSTR_OPARG": "{0p}->op.arg",
    # The size of an instruction of family {0}, in units of next_instr.
    "INSTRUCTION_SIZE_OF": "1 + INLINE_CACHE_ENTRIES_{0}",
    # The bytecode offset of the instruction at {0}, and the instruction at
    # bytecode offset {0}.
    "INSTR_OFFSET_OF": "{0} - _PyFrame_GetBytecode(frame)",
    "INSTR_AT_OFFSET": "_PyFrame_GetBytecode(frame) + {0}",
    # The bytecode offset of the instruction that is executing, from
    # next_instr, for exception_unwind.
    "CURRENT_OFFSET": "INSTR_OFFSET()-1",
    # The handler that runs an instruction whose original opcode, as the
    # instrumentation records it, is {0}.
    "ORIGINAL_HANDLER": "{0}",
}


def tokens_text(tkns: list[Token]) -> str:
    "The source text of tkns, with the spacing they have in the input"
    text = ""
    prev: Token | None = None
    for tkn in tkns:
        if prev is not None:
            if prev.end_line < tkn.line:
                text += " "
            else:
                text += " " * (tkn.column - prev.end_column)
        text += tkn.text
        prev = tkn
    return text


def find_local(name: str, storage: Storage) -> Local | None:
    for var in storage.inputs + storage.outputs:
        if var.name == name:
            return var
    return None


def matching_rparen(tkns: list[Token], lparen: int) -> int:
    depth = 0
    for i in range(lparen, len(tkns)):
        if tkns[i].kind == "LPAREN":
            depth += 1
        elif tkns[i].kind == "RPAREN":
            depth -= 1
            if depth == 0:
                return i
    return -1


def forget_stored_pointers(uop: CodeSection, storage: Storage) -> None:
    """Before a loop body: a later iteration may see a value assigned by an
    earlier one, which need not be a pointer."""
    stored = {tkn.text for tkn in uop.local_stores}
    for var in storage.inputs + storage.outputs:
        if var.name in stored:
            var.known_object = False


# Instructions whose boxes of inline inputs are counted as container stores
# (Py_STATS object_stats.value_boxes, pycore_stats.h)
CONTAINER_STORES = (
    "STORE_SUBSCR", "STORE_SLICE", "LIST_APPEND", "LIST_EXTEND", "SET_ADD",
    "SET_UPDATE", "MAP_ADD", "DICT_UPDATE", "DICT_MERGE", "BUILD_",
    "STORE_GLOBAL", "STORE_NAME", "STORE_DEREF",
)


def box_kind(inst_name: str) -> str:
    """What a box made by inst_name is for, as a _PY_BOX_* class."""
    name = inst_name.removeprefix("INSTRUMENTED_")
    if name.startswith(CONTAINER_STORES):
        return "_PY_BOX_CONTAINER_STORE"
    if name.startswith("STORE_ATTR"):
        return "_PY_BOX_ATTRIBUTE_STORE"
    if name.startswith("CALL"):
        return "_PY_BOX_CALL"
    if name == "INTERPRETER_EXIT":
        return "_PY_BOX_RETURN"
    return "_PY_BOX_OTHER"


class Emitter:
    out: CWriter
    labels: dict[str, Label]
    _replacers: dict[str, ReplacementFunctionType]
    cannot_escape: bool
    jump_prefix: str
    instruction_macros: dict[str, str] = STACK_INSTRUCTION_MACROS

    def __init__(self, out: CWriter, labels: dict[str, Label], cannot_escape: bool = False, jump_prefix: str = ""):
        self._replacers = {
            "EXIT_IF": self.exit_if,
            "DEOPT_IF": self.deopt_if,
            "ERROR_IF": self.error_if,
            "ERROR_NO_POP": self.error_no_pop,
            "DEAD": self.kill,
            "INPUTS_DEAD": self.kill_inputs,
            "SYNC_SP": self.sync_sp,
            "SAVE_STACK": self.save_stack,
            "RELOAD_STACK": self.reload_stack,
            "DISPATCH": self.dispatch,
            "INSTRUCTION_SIZE": self.instruction_size,
            "stack_pointer": self.stack_pointer,
            "Py_UNREACHABLE": self.unreachable,
        }
        for name in self.instruction_macros:
            self._replacers[name] = self.instruction_macro
        self.out = out
        self.labels = labels
        self.cannot_escape = cannot_escape
        self.jump_prefix = jump_prefix

    def dispatch(
        self,
        tkn: Token,
        tkn_iter: TokenIterator,
        uop: CodeSection,
        storage: Storage,
        inst: Instruction | None,
    ) -> bool:
        if storage.spilled:
            raise analysis_error("stack_pointer needs reloading before dispatch", tkn)
        storage.stack.flush(self.out)
        self.emit(tkn)
        return False

    def unreachable(
        self,
        tkn: Token,
        tkn_iter: TokenIterator,
        uop: CodeSection,
        storage: Storage,
        inst: Instruction | None,
    ) -> bool:
        self.emit(tkn)
        emit_to(self.out, tkn_iter, "SEMI")
        self.emit(";\n")
        return False

    def deopt_if(
        self,
        tkn: Token,
        tkn_iter: TokenIterator,
        uop: CodeSection,
        storage: Storage,
        inst: Instruction | None,
    ) -> bool:
        self.out.start_line()
        self.out.emit("if (")
        lparen = next(tkn_iter)
        assert lparen.kind == "LPAREN"
        first_tkn = tkn_iter.peek()
        emit_to(self.out, tkn_iter, "RPAREN")
        self.emit(") {\n")
        next(tkn_iter)  # Semi colon
        self.emit_jump_to_predicted(inst)
        self.emit("}\n")
        return not always_true(first_tkn)

    exit_if = deopt_if

    def emit_jump_to_predicted(self, inst: Instruction | None) -> None:
        assert inst is not None
        assert inst.family is not None
        family_name = inst.family.name
        self.emit(f"UPDATE_MISS_STATS({family_name});\n")
        self.emit(f"assert(_PyOpcode_Deopt[opcode] == ({family_name}));\n")
        self.emit(f"JUMP_TO_PREDICTED({self.jump_prefix}{family_name});\n")

    def emit_object_inputs(
        self, uop: Uop, storage: Storage, inst: Instruction | None, stack_read_later: bool
    ) -> None:
        """Make each input that uop converts to PyObject * hold a pointer.

        A guard exits if the input holds an inline value; any other uop boxes
        the value, by value so that the input can stay in a register. Either
        way the input is known to be an object for the rest of the
        instruction. The test is marked unlikely, so the boxing code goes out
        of line. See "Inline values" in interpreter_definition.md.

        The box is written back to the input's stack slot only if something
        can still read that slot: the input outlives the uop, or
        stack_read_later says that a deopt, exit, escaping call or error
        without pop may follow.
        """
        for var in storage.inputs:
            if var.name in uop.asserted_objects:
                var.known_object = True
        if uop.properties.inline_ok:
            return
        guard = uop.is_guard()
        peeks = {item.name for item in uop.stack.inputs if item.peek}
        # Boxed inputs whose stack slot still holds the inline value.
        unsynced: list[Local] = []
        for var in storage.inputs:
            if var.name not in uop.object_inputs or var.known_object:
                continue
            self.out.start_line()
            # Test the stack slot rather than the local where the slot holds
            # the value, which is cheaper (see _PyValue_TopBitsAt()).
            ref = var.name
            at = ""
            if var.memory_offset is not None:
                ref = f"&{storage.stack.address(var.memory_offset)}"
                at = "At"
            if guard:
                self.emit(f"if (Py_UNLIKELY(!_PyValue_IsPointerSpace{at}({ref}))) {{\n")
                self.emit_jump_to_predicted(inst)
            else:
                test = "_PyValue_IsInlineAt" if at else "PyValue_IsInline"
                self.emit(f"if (Py_UNLIKELY({test}({ref}))) {{\n")
                self.emit(f"{var.name} = PyValue_Box({var.name});\n")
                # A failed box leaves the value inline. Every input is still
                # live, so leave them all to exception_unwind, boxes included.
                self.emit(f"if (PyValue_IsInline({var.name})) {{\n")
                for other in unsynced:
                    self.emit_store_input(other, storage)
                storage.stack.copy().flush(self.out)
                self.emit(f"{self.jump_prefix}JUMP_TO_LABEL(error);\n")
                self.emit("}\n")
                if inst is not None:
                    self.emit(f"BOX_STAT_INC({inst.name}, {box_kind(inst.name)});\n")
                if var.memory_offset is not None:
                    if var.name in peeks or stack_read_later:
                        self.emit_store_input(var, storage)
                    else:
                        unsynced.append(var)
            self.emit("}\n")
            var.known_object = True

    def emit_store_input(self, var: Local, storage: Storage) -> None:
        assert var.memory_offset is not None
        self.out.start_line()
        storage.stack.store(self.out, var, var.memory_offset)

    def goto_error(self, offset: int, storage: Storage) -> str:
        if offset > 0:
            return f"{self.jump_prefix}JUMP_TO_LABEL(pop_{offset}_error);"
        if offset < 0:
            storage.copy().flush(self.out)
        return f"{self.jump_prefix}JUMP_TO_LABEL(error);"

    def error_if(
        self,
        tkn: Token,
        tkn_iter: TokenIterator,
        uop: CodeSection,
        storage: Storage,
        inst: Instruction | None,
    ) -> bool:
        lparen = next(tkn_iter)
        assert lparen.kind == "LPAREN"
        first_tkn = tkn_iter.peek()
        unconditional = always_true(first_tkn)
        if unconditional:
            next(tkn_iter)
            next(tkn_iter)  # RPAREN
            self.out.start_line()
        else:
            self.out.emit_at("if ", tkn)
            self.emit(lparen)
            emit_to(self.out, tkn_iter, "RPAREN")
            self.out.emit(") {\n")
        next(tkn_iter)  # Semi colon
        storage.clear_inputs("at ERROR_IF")

        c_offset = storage.stack.sp_offset()
        try:
            offset = int(c_offset)
        except ValueError:
            offset = -1
        self.out.emit(self.goto_error(offset, storage))
        self.out.emit("\n")
        if not unconditional:
            self.out.emit("}\n")
        return not unconditional

    def error_no_pop(
        self,
        tkn: Token,
        tkn_iter: TokenIterator,
        uop: CodeSection,
        storage: Storage,
        inst: Instruction | None,
    ) -> bool:
        next(tkn_iter)  # LPAREN
        next(tkn_iter)  # RPAREN
        next(tkn_iter)  # Semi colon
        self.out.emit_at(self.goto_error(0, storage), tkn)
        return False

    def kill_inputs(
        self,
        tkn: Token,
        tkn_iter: TokenIterator,
        uop: CodeSection,
        storage: Storage,
        inst: Instruction | None,
    ) -> bool:
        next(tkn_iter)
        next(tkn_iter)
        next(tkn_iter)
        for var in storage.inputs:
            var.kill()
        return True

    def kill(
        self,
        tkn: Token,
        tkn_iter: TokenIterator,
        uop: CodeSection,
        storage: Storage,
        inst: Instruction | None,
    ) -> bool:
        next(tkn_iter)
        name_tkn = next(tkn_iter)
        name = name_tkn.text
        next(tkn_iter)
        next(tkn_iter)
        for var in storage.inputs:
            if var.name == name:
                var.kill()
                break
        else:
            raise analysis_error(
                f"'{name}' is not a live input-only variable", name_tkn
            )
        return True

    def sync_sp(
        self,
        tkn: Token,
        tkn_iter: TokenIterator,
        uop: CodeSection,
        storage: Storage,
        inst: Instruction | None,
    ) -> bool:
        next(tkn_iter)
        next(tkn_iter)
        next(tkn_iter)
        storage.clear_inputs("when syncing stack")
        storage.flush(self.out)
        storage.stack.clear(self.out)
        return True

    def stack_pointer(
        self,
        tkn: Token,
        tkn_iter: TokenIterator,
        uop: CodeSection,
        storage: Storage,
        inst: Instruction | None,
    ) -> bool:
        if storage.spilled:
            raise analysis_error("stack_pointer is invalid when stack is spilled to memory", tkn)
        self.emit(tkn)
        return True

    def goto_label(self, goto: Token, label: Token, storage: Storage) -> None:
        if label.text not in self.labels:
            print(self.labels.keys())
            raise analysis_error(f"Label '{label.text}' does not exist", label)
        label_node = self.labels[label.text]
        if label_node.spilled:
            if not storage.spilled:
                self.emit_save(storage)
        elif storage.spilled:
            raise analysis_error("Cannot jump from spilled label without reloading the stack pointer", goto)
        self.out.start_line()
        self.out.emit(f"{self.jump_prefix}JUMP_TO_LABEL(")
        self.out.emit(label)
        self.out.emit(")")

    def emit_save(self, storage: Storage) -> None:
        storage.flush(self.out)
        storage.save(self.out)

    def save_stack(
        self,
        tkn: Token,
        tkn_iter: TokenIterator,
        uop: CodeSection,
        storage: Storage,
        inst: Instruction | None,
    ) -> bool:
        next(tkn_iter)
        next(tkn_iter)
        next(tkn_iter)
        self.emit_save(storage)
        return True

    def emit_reload(self, storage: Storage) -> None:
        storage.reload(self.out)

    def reload_stack(
        self,
        tkn: Token,
        tkn_iter: TokenIterator,
        uop: CodeSection,
        storage: Storage,
        inst: Instruction | None,
    ) -> bool:
        next(tkn_iter)
        next(tkn_iter)
        next(tkn_iter)
        storage.flush(self.out)
        storage.full_reload(self.out)
        return True

    def instruction_size(self,
        tkn: Token,
        tkn_iter: TokenIterator,
        uop: CodeSection,
        storage: Storage,
        inst: Instruction | None,
    ) -> bool:
        """Replace the INSTRUCTION_SIZE macro with the size of the current instruction."""
        if uop.instruction_size is None:
            raise analysis_error("The INSTRUCTION_SIZE macro requires uop.instruction_size to be set", tkn)
        self.out.emit(f" {uop.instruction_size}u ")
        return True

    def instruction_macro_args(self, tkn: Token, tkn_iter: TokenIterator) -> tuple[list[list[Token]], Token]:
        lparen = next(tkn_iter)
        if lparen.kind != "LPAREN":
            raise analysis_error(f"Expected '(' after {tkn.text}", lparen)
        args: list[list[Token]] = [[]]
        depth = 0
        for t in tkn_iter:
            if t.kind == "RPAREN" and depth == 0:
                if args == [[]]:
                    args = []
                return args, t
            if t.kind in ("LPAREN", "LBRACKET"):
                depth += 1
            elif t.kind in ("RPAREN", "RBRACKET"):
                depth -= 1
            if t.kind == "COMMA" and depth == 0:
                args.append([])
            else:
                if t.text in self._replacers:
                    raise analysis_error(f"{t.text} in an argument of {tkn.text}", t)
                args[-1].append(t)
        raise analysis_error(f"Unterminated {tkn.text}", tkn)

    def expand_instruction_macro(self, tkn: Token, args: list[list[Token]], inst: Instruction | None) -> str:
        template = self.instruction_macros[tkn.text]
        texts = [tokens_text(arg) for arg in args]
        values = {str(i): text for i, text in enumerate(texts)}
        if args:
            values["0p"] = texts[0] if len(args[0]) == 1 else f"({texts[0]})"
        def substitute(m: re.Match[str]) -> str:
            if m.group(1) not in values:
                raise analysis_error(f"Wrong number of arguments to {tkn.text}", tkn)
            return values[m.group(1)]
        return re.sub(r"\{(\w+)\}", substitute, template)

    def instruction_macro(
        self,
        tkn: Token,
        tkn_iter: TokenIterator,
        uop: CodeSection,
        storage: Storage,
        inst: Instruction | None,
    ) -> bool:
        """Expand a macro of STACK_INSTRUCTION_MACROS. The text takes the place
        of the macro and its arguments, so spacing around it is kept."""
        args, rparen = self.instruction_macro_args(tkn, tkn_iter)
        text = self.expand_instruction_macro(tkn, args, inst)
        self.out.maybe_dedent(text)
        self.out.emit_at(text, tkn)
        self.out.maybe_indent(text)
        self.out.last_token = rparen
        return True

    def _print_storage(self, reason:str, storage: Storage) -> None:
        if DEBUG:
            self.out.start_line()
            self.emit(f"/* {reason} */\n")
            self.emit(storage.as_comment())
            self.out.start_line()

    def _emit_stmt(
        self,
        stmt: Stmt,
        uop: CodeSection,
        storage: Storage,
        inst: Instruction | None,
    ) -> tuple[bool, Token | None, Storage]:
        method_name = "emit_" + stmt.__class__.__name__
        method = getattr(self, method_name, None)
        if method is None:
            raise NotImplementedError
        return method(stmt, uop, storage, inst) # type: ignore[no-any-return]

    def emit_SimpleStmt(
        self,
        stmt: SimpleStmt,
        uop: CodeSection,
        storage: Storage,
        inst: Instruction | None,
    ) -> tuple[bool, Token | None, Storage]:
        local_stores = set(uop.local_stores)
        reachable = True
        tkn = stmt.contents[-1]
        try:
            if stmt in uop.properties.escaping_calls and not self.cannot_escape:
                storage.stack.escaping = True
                try:
                    self.emit_save(storage)
                finally:
                    storage.stack.escaping = False
            tkn_iter = TokenIterator(stmt.contents)
            for tkn in tkn_iter:
                if tkn.kind == "GOTO":
                    label_tkn = next(tkn_iter)
                    self.goto_label(tkn, label_tkn, storage)
                    reachable = False
                elif tkn.kind == "RETURN":
                    self.emit(tkn)
                    semicolon = emit_to(self.out, tkn_iter, "SEMI")
                    self.emit(semicolon)
                    reachable = False
                elif tkn.kind == "IDENTIFIER":
                    if tkn.text in self._replacers:
                        if not self._replacers[tkn.text](tkn, tkn_iter, uop, storage, inst):
                            reachable = False
                    else:
                        if tkn in local_stores:
                            for var in storage.inputs:
                                if var.name == tkn.text:
                                    var.in_local = True
                                    var.memory_offset = None
                                    var.known_object = False
                                    var.ir_field = None
                                    break
                            for var in storage.outputs:
                                if var.name == tkn.text:
                                    var.in_local = True
                                    var.memory_offset = None
                                    var.known_object = False
                                    var.ir_field = None
                                    break
                        if tkn.text.startswith("DISPATCH"):
                            reachable = False
                        self.out.emit(tkn)
                else:
                    self.out.emit(tkn)
            self.note_pointer_assignment(stmt, storage)
            if stmt in uop.properties.escaping_calls and not self.cannot_escape:
                self.emit_reload(storage)
            return reachable, None, storage
        except StackError as ex:
            raise analysis_error(ex.args[0], tkn) #from None


    def note_pointer_assignment(self, stmt: SimpleStmt, storage: Storage) -> None:
        """After `a = b;` with b known to hold a pointer, or `a = C(...);` with
        C in POINTER_CONSTRUCTORS, a is known to hold a pointer too."""
        tkns = stmt.contents
        if len(tkns) < 4 or tkns[1].kind != "EQUALS" or tkns[-1].kind != "SEMI":
            return
        if len(tkns) == 4:
            source = find_local(tkns[2].text, storage)
            if source is None or not source.known_object:
                return
        elif not (tkns[2].text in POINTER_CONSTRUCTORS and tkns[3].kind == "LPAREN"
                  and matching_rparen(tkns, 3) == len(tkns) - 2):
            return
        # A peeked item has one Local among the inputs and another among the
        # outputs of a copied storage; mark both, as the store cleared both.
        for var in storage.inputs + storage.outputs:
            if var.name == tkns[0].text:
                var.known_object = True

    def emit_MacroIfStmt(
        self,
        stmt: MacroIfStmt,
        uop: CodeSection,
        storage: Storage,
        inst: Instruction | None,
    ) -> tuple[bool, Token | None, Storage]:
        self.out.emit(stmt.condition)
        branch = stmt.else_ is not None
        reachable = True
        if_storage = storage
        else_storage = storage.copy()
        for s in stmt.body:
            r, tkn, if_storage = self._emit_stmt(s, uop, if_storage, inst)
            if tkn is not None:
                self.out.emit(tkn)
            if not r:
                reachable = False
        if branch:
            assert stmt.else_ is not None
            self.out.emit(stmt.else_)
            assert stmt.else_body is not None
            for s in stmt.else_body:
                r, tkn, else_storage = self._emit_stmt(s, uop, else_storage, inst)
                if tkn is not None:
                    self.out.emit(tkn)
                if not r:
                    reachable = False
            else_storage.merge(if_storage, self.out)
            storage = if_storage
        else:
            if_storage.merge(else_storage, self.out)
            storage = else_storage
        self.out.emit(stmt.endif)
        return reachable, None, storage


    def emit_IfStmt(
        self,
        stmt: IfStmt,
        uop: CodeSection,
        storage: Storage,
        inst: Instruction | None,
    ) -> tuple[bool, Token | None, Storage]:
        self.out.emit(stmt.if_)
        for tkn in stmt.condition:
            self.out.emit(tkn)
        if_storage = storage.copy()
        rbrace: Token | None = stmt.if_
        try:
            reachable, rbrace, if_storage = self._emit_stmt(stmt.body, uop, if_storage, inst)
            if stmt.else_ is not None:
                assert rbrace is not None
                self.out.emit(rbrace)
                self.out.emit(stmt.else_)
            if stmt.else_body is not None:
                else_reachable, rbrace, else_storage = self._emit_stmt(stmt.else_body, uop, storage, inst)
                if not reachable:
                    reachable, storage = else_reachable, else_storage
                elif not else_reachable:
                    # Discard the else storage
                    storage = if_storage
                else:
                    #Both reachable
                    else_storage.merge(if_storage, self.out)
                    storage = else_storage
            else:
                if reachable:
                    if_storage.merge(storage, self.out)
                    storage = if_storage
                else:
                    # Discard the if storage
                    reachable = True
            return reachable, rbrace, storage
        except StackError as ex:
            assert rbrace is not None
            raise analysis_error(ex.args[0], rbrace) from None

    def emit_BlockStmt(
        self,
        stmt: BlockStmt,
        uop: CodeSection,
        storage: Storage,
        inst: Instruction | None,
        emit_braces: bool = True,
    ) -> tuple[bool, Token | None, Storage]:
        """ Returns (reachable?, closing '}', stack)."""
        tkn: Token | None = None
        try:
            if emit_braces:
                self.out.emit(stmt.open)
            reachable = True
            for s in stmt.body:
                reachable, tkn, storage = self._emit_stmt(s, uop, storage, inst)
                if tkn is not None:
                    self.out.emit(tkn)
                if not reachable:
                    break
            return reachable, stmt.close, storage
        except StackError as ex:
            if tkn is None:
                tkn = stmt.close
            raise analysis_error(ex.args[0], tkn) from None

    def emit_ForStmt(
        self,
        stmt: ForStmt,
        uop: CodeSection,
        storage: Storage,
        inst: Instruction | None,
    ) -> tuple[bool, Token | None, Storage]:
        """ Returns (reachable?, closing '}', stack)."""
        self.out.emit(stmt.for_)
        for tkn in stmt.header:
            self.out.emit(tkn)
        forget_stored_pointers(uop, storage)
        reachable, brace, body_storage = self._emit_stmt(stmt.body, uop, storage.copy(), inst)
        body_storage.merge(storage, self.out)
        if brace is not None:
            self.out.emit(brace)
        return reachable, None, storage

    def emit_WhileStmt(
        self,
        stmt: WhileStmt,
        uop: CodeSection,
        storage: Storage,
        inst: Instruction | None,
    ) -> tuple[bool, Token | None, Storage]:
        """ Returns (reachable?, closing '}', stack)."""
        self.out.emit(stmt.while_)
        for tkn in stmt.condition:
            self.out.emit(tkn)
        forget_stored_pointers(uop, storage)
        return self._emit_stmt(stmt.body, uop, storage, inst)


    def emit_tokens(
        self,
        code: CodeSection,
        storage: Storage,
        inst: Instruction | None,
        emit_braces: bool = True
    ) -> tuple[bool, Storage]:
        self.out.start_line()
        reachable, tkn, storage = self.emit_BlockStmt(code.body, code, storage, inst, emit_braces)
        assert tkn is not None
        try:
            if reachable:
                storage.push_outputs()
            if emit_braces:
                self.out.emit(tkn)
        except StackError as ex:
            raise analysis_error(ex.args[0], tkn) from None
        return reachable, storage

    def emit(self, txt: str | Token) -> None:
        self.out.emit(txt)


def cflags(p: Properties) -> str:
    flags: list[str] = []
    if p.oparg:
        flags.append("HAS_ARG_FLAG")
    if p.uses_co_consts:
        flags.append("HAS_CONST_FLAG")
    if p.uses_co_names:
        flags.append("HAS_NAME_FLAG")
    if p.jumps:
        flags.append("HAS_JUMP_FLAG")
    if p.has_free:
        flags.append("HAS_FREE_FLAG")
    if p.uses_locals:
        flags.append("HAS_LOCAL_FLAG")
    if p.eval_breaker:
        flags.append("HAS_EVAL_BREAK_FLAG")
    if p.deopts:
        flags.append("HAS_DEOPT_FLAG")
    if p.side_exit:
        flags.append("HAS_EXIT_FLAG")
    if not p.infallible:
        flags.append("HAS_ERROR_FLAG")
    if p.error_without_pop:
        flags.append("HAS_ERROR_NO_POP_FLAG")
    if p.escapes:
        flags.append("HAS_ESCAPES_FLAG")
    if p.pure:
        flags.append("HAS_PURE_FLAG")
    if p.no_save_ip:
        flags.append("HAS_NO_SAVE_IP_FLAG")
    if p.sync_sp:
        flags.append("HAS_SYNC_SP_FLAG")
    if flags:
        return " | ".join(flags)
    else:
        return "0"
